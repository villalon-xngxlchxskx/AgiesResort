 ("DEMO-0027",27,4,40,37,"PAYMENT PENDING","pending"),
 # fresh unpaid holds
 ("DEMO-0028",28,1,18,33,"PENDING","none"),("DEMO-0029",29,3,27,31,"PENDING","none"),
