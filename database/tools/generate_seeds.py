#!/usr/bin/env python3
"""Generates seed_100_customers.sql and seed_demo_data.sql.

All people, emails and phone numbers are FICTIONAL.
- Emails use the reserved domain example.com (RFC 2606) and never reach anyone.
- Phone numbers use the obviously synthetic block 0999-000-0xxx.
Run:  python3 database/tools/generate_seeds.py   (from the project root)
"""
